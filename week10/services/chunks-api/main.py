@contextmanager
def db():
    conn = psycopg2.connect(DATABASE_URL)
    try:
        register_vector(conn)
        yield conn
    finally:
        conn.close()


def cursor(conn):
    return conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)


def wait_for_db(retries: int = 15, delay: int = 2) -> None:
    for attempt in range(1, retries + 1):
        try:
            psycopg2.connect(DATABASE_URL).close()
            return
        except psycopg2.OperationalError:
            print(f"DB not ready (attempt {attempt}/{retries})")
            time.sleep(delay)


def init_schema() -> None:
    raw = psycopg2.connect(DATABASE_URL)
    with raw, raw.cursor() as cur:
        cur.execute("CREATE EXTENSION IF NOT EXISTS vector")
    raw.close()
    with db() as conn, conn.cursor() as cur:
        # A pgdata volume from an earlier layout (corpora/indexes, chunks.corpus_id)
        # would survive CREATE IF NOT EXISTS. Nothing there is worth keeping: drop it.
        cur.execute("""
            DO $$ BEGIN
              IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = 'chunks')
                 AND NOT EXISTS (SELECT 1 FROM information_schema.columns
                                 WHERE table_name = 'chunks' AND column_name = 'bucket_id') THEN
                DROP TABLE IF EXISTS vectors, chunks, indexes, corpora CASCADE;
              END IF;
            END $$;
        """)
        cur.execute("""
            CREATE TABLE IF NOT EXISTS buckets (
                id             TEXT PRIMARY KEY,
                name           TEXT NOT NULL,
                created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                retriever      TEXT,
                status         TEXT NOT NULL DEFAULT 'empty',   -- empty | indexing | ready | error
                chunk_count    INTEGER NOT NULL DEFAULT 0,
                embedded_count INTEGER NOT NULL DEFAULT 0,
                parquet_sha    TEXT,
                error          TEXT,
                indexed_at     TIMESTAMPTZ
            );
            -- the chunker config from manifest.json, when imported as a zip
            ALTER TABLE buckets ADD COLUMN IF NOT EXISTS chunker JSONB;
            ALTER TABLE buckets ADD COLUMN IF NOT EXISTS kind TEXT NOT NULL DEFAULT 'chunks';  -- chunks | descriptions
            -- VECTOR without a dimension: buckets with 384d and 768d models share
            -- the table. Exact scan filtered by bucket_id; ponytail: HNSW per dim
            -- if a bucket grows 100x.
            CREATE TABLE IF NOT EXISTS chunks (
                bucket_id   TEXT NOT NULL REFERENCES buckets(id) ON DELETE CASCADE,
                chunk_id    TEXT NOT NULL,
                filename    TEXT NOT NULL,
                chunk_index INTEGER NOT NULL,
                pages       JSONB,
                heading     TEXT,
                text        TEXT NOT NULL,
                embedding   VECTOR,
                PRIMARY KEY (bucket_id, chunk_id)
            );
            -- The gabarito travels with the corpus it was resolved against: a
            -- chunk_id only means something inside its own bucket.
            CREATE TABLE IF NOT EXISTS qrels (
                bucket_id TEXT NOT NULL REFERENCES buckets(id) ON DELETE CASCADE,
                query_id  TEXT NOT NULL,
                chunk_id  TEXT NOT NULL,
                part      INTEGER NOT NULL DEFAULT 0,
                coverage  REAL,
                PRIMARY KEY (bucket_id, query_id, chunk_id, part)
            );
            -- a descriptions bucket's rows: layer 1 of the two-layer search
            CREATE TABLE IF NOT EXISTS documents (
                bucket_id   TEXT NOT NULL REFERENCES buckets(id) ON DELETE CASCADE,
                filename    TEXT NOT NULL,
                description TEXT NOT NULL,
                embedding   VECTOR,
                PRIMARY KEY (bucket_id, filename)
            );
        """)
        # A background embedding dies with the process (restart, --reload). Its
        # bucket would otherwise sit at 'indexing' forever with no way to retry.
        cur.execute("""
            UPDATE buckets SET status = 'error', error = 'indexing interrupted by API restart — upload again'
            WHERE status = 'indexing'
        """)
        conn.commit()


def vector_name(retriever: str) -> str:
    """The vector model behind a retriever: itself, or the one a hybrid wraps."""
    return RETRIEVERS[retriever].get("vector", retriever)


def encode(retriever: str, texts: list[str], query: bool) -> np.ndarray:
    """Unit vectors for texts, one row each: Voyage's API, or a local sentence-transformers model."""
    spec = RETRIEVERS[vector_name(retriever)]
    if spec["model"].startswith("voyage:"):
        return voyage_embed(spec["model"].removeprefix("voyage:"), texts, "query" if query else "document")
    prefix = spec["query" if query else "passage"]
    return embedder(retriever).encode([prefix + t for t in texts], normalize_embeddings=True)


def embedder(name: str):
    name = vector_name(name)
    with _embed_lock:
        if name not in _embedders:
            import torch
            from sentence_transformers import SentenceTransformer
            print(f"Loading {RETRIEVERS[name]['model']}…")
            # Force fp32: checkpoints saved in bf16 (Qwen3) would otherwise run
            # bf16 matmuls on CPU, which has no fast kernel here — 50x slower.
            _embedders[name] = SentenceTransformer(
                RETRIEVERS[name]["model"], model_kwargs={"torch_dtype": torch.float32}
            )
        return _embedders[name]


def reranker(name: str):
    with _embed_lock:
        if name not in _rerankers:
            import torch
            from sentence_transformers import CrossEncoder
            print(f"Loading {RERANKERS[name]}…")
            _rerankers[name] = CrossEncoder(
                RERANKERS[name], max_length=RERANK_PROMPTS.get(name, PLAIN_PROMPT)[2],
                model_kwargs={"torch_dtype": torch.float32}
            )
        return _rerankers[name]


_stemmer = Stemmer.Stemmer("portuguese")
# Numbers joined by / or - stay one token ("8666/93", "12/03/2020"), so exact
# references don't dissolve into "8", "666", "93". Thousand-separator dots
# go first, so "8.666" == "8666"; other dots still split words.
TOKEN_RE = re.compile(r"\d+(?:[/-]\d+)+|\w+")
DIGIT_DOT_RE = re.compile(r"(?<=\d)\.(?=\d)")


def strip_accents(text: str) -> str:
    return "".join(c for c in unicodedata.normalize("NFD", text) if not unicodedata.combining(c))


def tokenize(text: str) -> list[str]:
    # Stem, strip accents, stem again: Snowball's rules need accents, but the
    # second pass folds what's left so "decisão", "decisões" and "decisao" meet.
    # ponytail: a few pairs still split (notificação→notific, notificacao→notificac).
    words = _stemmer.stemWords(TOKEN_RE.findall(DIGIT_DOT_RE.sub("", text.lower())))
    return _stemmer.stemWords([strip_accents(w) for w in words])


ACRONYM_RE = re.compile(r"\(([A-ZÀ-Ý]{2,10})\)")
CONNECTORS = {"de", "da", "do", "das", "dos", "e", "em", "para", "a", "o", "of", "the", "and"}


def mine_acronyms(texts: list[str]) -> dict[str, list[str]]:
    """{acronym token: expansion tokens} from "Junta Administrativa de Recursos (JAR)".

    Walks back from each "(SIGLA)" matching initials of non-connector words.
    First definition wins; a sigla with no matching words is ignored."""
    found: dict[str, list[str]] = {}
    for text in texts:
        for m in ACRONYM_RE.finditer(text):
            sigla = strip_accents(m.group(1))
            words = re.findall(r"\w+", text[max(0, m.start() - 200):m.start()])
            initials, start = "", len(words)
            for i in range(len(words) - 1, -1, -1):
                if words[i].lower() in CONNECTORS:
                    continue
                initials = strip_accents(words[i][0]).upper() + initials
                if not sigla.endswith(initials):
                    break
                if initials == sigla:
                    start = i
                    break
            key = tokenize(sigla)
            if initials == sigla and len(key) == 1 and key[0] not in found.keys() | CONNECTORS:
                found[key[0]] = tokenize(" ".join(words[start:]))
    return found


def expand_query(tokens: list[str], acronyms: dict[str, list[str]]) -> list[str]:
    """Acronym in the query -> add its expansion; full expansion -> add the acronym."""
    extra = [t for tok in tokens for t in acronyms.get(tok, [])]
    extra += [a for a, exp in acronyms.items() if a not in tokens and set(exp) <= set(tokens)]
    return tokens + extra


