"""Chunks API: buckets.

bucket = one corpus.parquet + its answers.parquet (the gabarito) + one
retriever. Create it, upload into it, search it at /api/buckets/{id}/search,
read its gabarito at /api/buckets/{id}/answers. To compare retrievers, make two
buckets from the same pair of files.

retriever kinds: bm25 (in-RAM index), vector (pgvector cosine), hybrid
(bm25 + vector, fused by Reciprocal Rank Fusion). Any of them can be reranked
per search (`?rerank=<reranker>`): retrieve top-rerank_depth, rescore with a
cross-encoder, fuse its order with the first stage's (rerank_keep), cut to k. Both
default to RERANK_DEPTH/RERANK_KEEP and can be set per search. And the query itself can be rewritten per search
(`?variants=N`): N alternative phrasings, pre-generated by Claude into
rewrites.json (gen_rewrites.py), are each searched and the rankings fused by RRF.

Two kinds of bucket. `chunks`: the chunker's bucket.zip, as above.
`descriptions`: a description.parquet (filename, description — one summary per
document) + its own retriever, uploaded separately. A chunks search can take
one as its first layer (`?docs=<descriptions bucket>`): rank the descriptions,
keep the top doc_top documents, search only their chunks. Like ?rerank=, it is
a search option: any chunks bucket can use any descriptions bucket that covers
its files, and nothing is reindexed.

/api/search keeps the response shape of week01/week03 so `eval/` runs
unchanged; without `bucket=` it uses the most recently indexed bucket.
"""

