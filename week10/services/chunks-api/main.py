# ── upload + indexing ──────────────────────────────────────────────────────

def write_vectors(cur, table: str, key: str, bid: str, batch: list[tuple], vecs) -> None:
    # execute_values allows exactly one %s, so bucket_id rides inside each row.
    execute_values(
        cur,
        f"UPDATE {table} SET embedding = v.emb::vector FROM (VALUES %s) AS v(bid, id, emb) "
        f"WHERE {table}.bucket_id = v.bid AND {table}.{key} = v.id",
        [(bid, i, v.tolist()) for (i, _), v in zip(batch, vecs)],
        template="(%s, %s, %s::real[])",
    )


def embed_bucket(bid: str, retriever: str, docs: bool = False) -> None:
    spec = RETRIEVERS[vector_name(retriever)]
    table, key, col = ("documents", "filename", "description") if docs else ("chunks", "chunk_id", "text")
    try:
        with db() as conn, conn.cursor() as cur:
            cur.execute(f"SELECT {key}, {col} FROM {table} WHERE bucket_id = %s ORDER BY {key}", (bid,))
            rows = cur.fetchall()
        for i in range(0, len(rows), BATCH):
            batch = rows[i:i + BATCH]
            vecs = encode(retriever, [t for _, t in batch], query=False)
            with db() as conn, conn.cursor() as cur:
                write_vectors(cur, table, key, bid, batch, vecs)
                cur.execute("UPDATE buckets SET embedded_count = %s WHERE id = %s", (i + len(batch), bid))
                conn.commit()
        with db() as conn, conn.cursor() as cur:
            cur.execute("UPDATE buckets SET status = 'ready', indexed_at = NOW() WHERE id = %s", (bid,))
            conn.commit()
        print(f"bucket {bid} ready: {len(rows)} vectors ({retriever})")
    except Exception as e:  # keep the row so the UI can show what went wrong
        print(f"bucket {bid} failed: {e}")
        with db() as conn, conn.cursor() as cur:
            cur.execute("UPDATE buckets SET status = 'error', error = %s WHERE id = %s", (str(e)[:500], bid))
            conn.commit()


@app.post("/api/buckets/import", status_code=201)
async def import_zip(bg: BackgroundTasks, file: UploadFile = File(...), retriever: str = Form(...)):
    """One step: the chunker's bucket.zip + a retriever. Named `<chunker> · <retriever>`."""
    if retriever not in RETRIEVERS:
        raise HTTPException(400, f"unknown retriever; choose one of {list(RETRIEVERS)}")
    try:
        z = zipfile.ZipFile(io.BytesIO(await file.read()))
        corpus, answers = z.read("corpus.parquet"), z.read("answers.parquet")
        chunker = json.loads(z.read("manifest.json"))["config"]
    except (zipfile.BadZipFile, KeyError, ValueError) as e:
        raise HTTPException(400, f"not a chunker bucket.zip (corpus.parquet + answers.parquet + manifest.json): {e}")
    with db() as conn, cursor(conn) as cur:
        cur.execute("INSERT INTO buckets (id, name, chunker) VALUES (%s, %s, %s) RETURNING id",
                    (uuid.uuid4().hex[:8], f"{chunker['name']} · {retriever}", Json(chunker)))
        bid = cur.fetchone()["id"]
        conn.commit()
    try:
        return ingest(bid, bg, corpus, answers, retriever)
    except HTTPException:  # bad parquet: don't leave an empty bucket behind
        with db() as conn, conn.cursor() as cur:
            cur.execute("DELETE FROM buckets WHERE id = %s", (bid,))
            conn.commit()
        raise


